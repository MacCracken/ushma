//! `src/constants_private.cyr` — the private constants outside steam — and the completeness
//! proof for every `const` item in `rust-old/src` (port plan §4 step 6).
//!
//! A private constant isn't reachable through the oracle's API, so its value comes from its
//! literal in `rust-old/src`, parsed with Rust's own `f64::from_str` (`rustsrc.rs`; `KLEIBER_W`
//! is an IEEE `*` / `/` fold, evaluated in the same order as Rust's const evaluation). It is
//! proven by the golden rows that depend on it, and `probe_tables.py` re-parses every literal in
//! Python and checks each compiled value. Names: `_US_<MODULE>_<NAME>`.
//!
//! `complete` proves every `const` item in every module (outside its test module, fn-local ones
//! included) is generated by exactly one emitter, or excused with a reason, so a constant added
//! to the oracle can't be missed:
//! - public scalars: `src/constants.cyr` (`t_constants`);
//! - public table presets and `ALL_*` slices: the data files (`t_tables`);
//! - steam's private tables and constants: `src/steam_data.cyr` (`t_steam`);
//! - every other private constant: here.

use crate::cyr::{comment_line, f64_lit, header};
use crate::rustsrc::{ConstItem, const_items, eval_f64, eval_int};
use crate::{t_constants, t_steam, t_tables};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The private constants generated here: (module, name).
const PRIVATE: &[(&str, &str)] = &[
    ("bridge", "R"),
    ("bridge", "KLEIBER_W"),
    ("bridge", "STEFAN_BOLTZMANN"),
    ("bridge", "SKIN_EMISSIVITY"),
    ("bridge", "LATENT_HEAT_SWEAT"),
    ("cycle", "MAX_DIAGRAM_PREALLOC"),
    ("numerical", "STABILITY_ROUNDOFF"),
    ("stat", "DEBYE_X_MAX"),
];

/// Every `.rs` file under `rust-old/src`, as (module name, path), sorted.
fn sources(root: &Path) -> Result<Vec<(String, PathBuf)>, String> {
    let mut out = Vec::new();
    let mut dirs = vec![root.join("rust-old/src")];
    while let Some(dir) = dirs.pop() {
        let entries = std::fs::read_dir(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                dirs.push(path);
            } else if path.extension().is_some_and(|x| x == "rs") {
                let module = path
                    .file_stem()
                    .and_then(|s| s.to_str())
                    .unwrap_or_default()
                    .to_string();
                out.push((module, path));
            }
        }
    }
    out.sort();
    Ok(out)
}

fn read(path: &Path) -> Result<String, String> {
    std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))
}

/// Which emitter claims each `const` item, or why it is excused.
pub fn complete(root: &Path) -> Result<(), String> {
    let mut claims: BTreeMap<String, String> = BTreeMap::new();
    let mut claim = |path: String, who: &str| -> Result<(), String> {
        match claims.insert(path.clone(), who.to_string()) {
            Some(prev) => Err(format!("{path}: claimed by both {prev} and {who}")),
            None => Ok(()),
        }
    };
    for c in t_constants::all() {
        claim(c.path(), "t_constants")?;
    }
    for t in t_tables::all() {
        for p in &t.presets {
            claim(format!("{}::{}", t.module, p.rust), "t_tables")?;
        }
        claim(format!("{}::{}", t.module, t.all), "t_tables")?;
    }
    for name in t_steam::GENERATED {
        claim(format!("steam::{name}"), "t_steam")?;
    }
    for (name, why) in t_steam::EXCUSED {
        claim(format!("steam::{name}"), &format!("excused: {why}"))?;
    }
    for (m, n) in PRIVATE {
        claim(format!("{m}::{n}"), "t_private")?;
    }
    let mut found = Vec::new();
    for (module, path) in sources(root)? {
        for c in const_items(&module, &read(&path)?)? {
            found.push(c.path());
        }
    }
    let mut unclaimed = Vec::new();
    for p in &found {
        if claims.remove(p).is_none() {
            unclaimed.push(p.clone());
        }
    }
    if !unclaimed.is_empty() || !claims.is_empty() {
        return Err(format!(
            "const items: not generated or excused {unclaimed:?}; claimed but not in rust-old/src \
             {:?}",
            claims.keys().collect::<Vec<_>>()
        ));
    }
    Ok(())
}

/// The comment for a private const: its `///` / `//` block above, then its trailing `//`.
fn comment(src: &str, c: &ConstItem) -> String {
    let lines: Vec<&str> = src.lines().collect();
    let needle = format!("const {}:", c.name);
    let mut out = String::new();
    if let Some(at) = lines
        .iter()
        .position(|l| l.trim_start().starts_with(&needle))
    {
        let mut block = Vec::new();
        let mut k = at;
        while k > 0 {
            k -= 1;
            let l = lines[k].trim_start();
            match l
                .strip_prefix("///")
                .or_else(|| l.strip_prefix("//"))
                .map(|r| r.strip_prefix(' ').unwrap_or(r).trim_end())
            {
                Some(t) => block.push(t.to_string()),
                None => break,
            }
        }
        block.reverse();
        for b in block {
            let _ = writeln!(out, "{}", comment_line(&b));
        }
    }
    if let Some(t) = &c.trailing {
        let _ = writeln!(out, "{}", comment_line(t));
    }
    out
}

pub fn emit(root: &Path, provenance: &str) -> Result<String, String> {
    complete(root)?;
    let mut out = header(
        "private constants (outside steam)",
        provenance,
        &[
            "Each is its literal in rust-old/src, parsed with Rust's f64::from_str and written as a\n\
             round-trip decimal (an expression is folded as Rust's const evaluation folds it). They\n\
             are private to their module (`_US_<MODULE>_`); probe_tables.py re-parses every literal\n\
             independently and checks each compiled value.",
        ],
    );
    let mut cache: BTreeMap<&str, (String, Vec<ConstItem>)> = BTreeMap::new();
    for &(module, name) in PRIVATE {
        if !cache.contains_key(module) {
            let src = read(&root.join(format!("rust-old/src/{module}.rs")))?;
            let items = const_items(module, &src)?;
            cache.insert(module, (src, items));
        }
        let (src, items) = &cache[module];
        let c = items
            .iter()
            .find(|c| c.name == name)
            .ok_or_else(|| format!("{module}.rs: no const {name}"))?;
        out.push_str(&comment(src, c));
        let place = c
            .in_fn
            .as_ref()
            .map_or_else(String::new, |f| format!("{f}::"));
        let _ = writeln!(
            out,
            "# Rust: ushma::{module}::{place}{name} (private{}) = {}",
            if c.in_fn.is_some() { ", fn-local" } else { "" },
            c.expr
        );
        let lit = match c.ty.as_str() {
            "f64" => f64_lit(eval_f64(&c.expr)?)?,
            "usize" | "u32" | "i64" | "i32" => eval_int(&c.expr)?.to_string(),
            other => return Err(format!("{module}::{name}: type {other}")),
        };
        let _ = writeln!(out, "const _US_{}_{name} = {lit};\n", module.to_uppercase());
    }
    Ok(out.trim_end().to_string() + "\n")
}
